in="authors_list_from_db.txt"
out="authors_list_clean_nfc.txt"

# Remove CRLF, BOM
uconv -x any-nfc "$in"      | \
tr -d '\r' | \
sed 's/^\xEF\xBB\xBF//'     | \
# Remove duplicate spaces & empty lines
sed 's/  */ /g'             | \
# Remove trailing spaces
sed 's/[[:blank:]]*$//'     | \
# Replace ' by `'
sed "s/'/\`/g"              | \
# Remove lines that are empty *after* cleaning
sed '/^[[:space:]]*$/d'     \
> "$out"

wc -l $in $out
diff -u  $in $out
